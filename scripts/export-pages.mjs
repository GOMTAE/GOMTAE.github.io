import { readdir, readFile, writeFile, mkdir, unlink } from "node:fs/promises";
import { resolve, dirname, relative, join } from "node:path";
import { fileURLToPath } from "node:url";

const marker = "Generated by Eleventy";
const fixedRoutes = new Set([
  "index.html",
  "projects.html",
  "publications.html",
  "writing.html",
  "work.html",
  "404.html",
  "feed.xml",
  "sitemap.xml",
]);
const isAllowed = (path) =>
  fixedRoutes.has(path) ||
  /^writing\/[a-z0-9]+(?:-[a-z0-9]+)*\/index\.html$/.test(path);
async function readOptional(path) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}
async function walk(path, base = path) {
  const files = [];
  for (const entry of await readdir(path, { withFileTypes: true })) {
    if (entry.isSymbolicLink())
      throw new Error("Refusing symbolic links in staging.");
    const destination = join(path, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(destination, base)));
    else files.push(relative(base, destination));
  }
  return files.sort();
}
export async function exportPages(root = process.cwd()) {
  const stage = resolve(root, ".site-build");
  const manifestPath = resolve(root, ".generated-pages.json");
  const previous = JSON.parse((await readOptional(manifestPath)) || "[]");
  const routes = await walk(stage);
  const prepared = [];
  // Validate the entire export before touching any deployed file.
  for (const route of [...routes, ...previous]) {
    if (!isAllowed(route))
      throw new Error(`Refusing to export unexpected route: ${route}`);
  }
  for (const route of routes) {
    const source = await readFile(join(stage, route), "utf8");
    if (!source.includes(marker))
      throw new Error(`Missing generated marker: ${route}`);
    const current = await readOptional(join(root, route));
    const isLegacyRoot =
      ["index.html", "projects.html", "publications.html"].includes(route) &&
      current?.includes("Massively by HTML5 UP");
    if (current && !current.includes(marker) && !isLegacyRoot)
      throw new Error(`Refusing to overwrite handwritten content: ${route}`);
    prepared.push([route, source]);
  }
  for (const route of previous.filter((route) => !routes.includes(route))) {
    const current = await readOptional(join(root, route));
    if (current && !current.includes(marker))
      throw new Error(`Refusing to remove handwritten content: ${route}`);
  }
  for (const [route, source] of prepared) {
    await mkdir(dirname(join(root, route)), { recursive: true });
    await writeFile(join(root, route), source);
  }
  for (const route of previous.filter((route) => !routes.includes(route))) {
    if ((await readOptional(join(root, route))) !== null)
      await unlink(join(root, route));
  }
  await writeFile(manifestPath, `${JSON.stringify(routes, null, 2)}\n`);
  console.log(
    `Exported ${routes.length} static pages/feeds. Publication microsites untouched.`,
  );
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await exportPages();
