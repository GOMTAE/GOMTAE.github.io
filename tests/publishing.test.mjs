import { test } from "node:test";
import assert from "node:assert/strict";
import {
  mkdtemp,
  mkdir,
  writeFile,
  readFile,
  cp,
  symlink,
  rm,
  access,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { exportPages } from "../scripts/export-pages.mjs";

const root = resolve(".");
const exists = (path) =>
  access(path).then(
    () => true,
    () => false,
  );
const generated = "<!-- Generated by Eleventy -->\n";

test("publishing Markdown generates readable HTML, feed and sitemap; drafts and future posts stay out", async () => {
  const fixture = await mkdtemp(join(tmpdir(), "portfolio-publishing-"));
  try {
    await cp(join(root, "src"), join(fixture, "src"), { recursive: true });
    await cp(
      join(root, "eleventy.config.js"),
      join(fixture, "eleventy.config.js"),
    );
    await writeFile(join(fixture, "package.json"), '{"type":"module"}');
    await mkdir(join(fixture, "assets/portfolio/media"), { recursive: true });
    await cp(
      join(root, "assets/portfolio/media/dimensions.json"),
      join(fixture, "assets/portfolio/media/dimensions.json"),
    );
    await symlink(join(root, "node_modules"), join(fixture, "node_modules"));
    await writeFile(
      join(fixture, "src/posts/published.md"),
      '---\ntitle: "A technical note & a test"\nslug: technical-note\ndate: 2026-01-10\nsummary: "An honest summary <with> details."\ntags: [Perception, Engineering]\ndraft: false\nrelatedProject: /publications/ssp.html\n---\n## A useful example\n\n```python\nprint("hello")\n```\n\n| Input | Output |\n| --- | --- |\n| One | Two |\n',
    );
    await writeFile(
      join(fixture, "src/posts/draft.md"),
      "---\ntitle: DRAFT_SENTINEL\nsummary: Not public\ndate: 2026-01-11\ndraft: true\n---\nPrivate draft.",
    );
    await writeFile(
      join(fixture, "src/posts/future.md"),
      "---\ntitle: FUTURE_SENTINEL\nsummary: Not yet public\ndate: 2099-01-11\n---\nScheduled.",
    );
    execFileSync(
      process.execPath,
      [join(root, "node_modules/@11ty/eleventy/cmd.cjs")],
      { cwd: fixture, stdio: "pipe" },
    );
    await exportPages(fixture);
    const article = await readFile(
      join(fixture, "writing/technical-note/index.html"),
      "utf8",
    );
    assert.match(article, /A technical note &amp; a test/);
    assert.match(article, /language-python/);
    assert.match(article, /token (keyword|string)/);
    assert.match(article, /<table>/);
    assert.match(article, /BlogPosting/);
    assert.match(
      article,
      /https:\/\/gomtae.github.io\/writing\/technical-note\//,
    );
    for (const route of [
      "writing.html",
      "index.html",
      "feed.xml",
      "sitemap.xml",
    ]) {
      const text = await readFile(join(fixture, route), "utf8");
      assert.doesNotMatch(text, /DRAFT_SENTINEL|FUTURE_SENTINEL/);
      assert.match(text, /technical-note/);
    }
    assert.equal(
      await exists(join(fixture, "writing/draft/index.html")),
      false,
    );
    assert.equal(
      await exists(join(fixture, "writing/future/index.html")),
      false,
    );
    // Unpublishing removes only the prior generated article, preventing stale pages.
    await writeFile(
      join(fixture, "src/posts/published.md"),
      "---\ntitle: A technical note\nsummary: Unpublished\ndate: 2026-01-10\ndraft: true\n---\nNo longer published.",
    );
    await rm(join(fixture, ".site-build"), { recursive: true });
    execFileSync(
      process.execPath,
      [join(root, "node_modules/@11ty/eleventy/cmd.cjs")],
      { cwd: fixture, stdio: "pipe" },
    );
    await exportPages(fixture);
    assert.equal(
      await exists(join(fixture, "writing/technical-note/index.html")),
      false,
    );
    assert.doesNotMatch(
      await readFile(join(fixture, "feed.xml"), "utf8"),
      /technical-note/,
    );
  } finally {
    await rm(fixture, { recursive: true, force: true });
  }
});

test("export rejects unexpected routes before making any writes", async () => {
  const fixture = await mkdtemp(join(tmpdir(), "portfolio-export-"));
  try {
    await mkdir(join(fixture, ".site-build/publications"), { recursive: true });
    await writeFile(
      join(fixture, ".site-build/index.html"),
      generated + "New home",
    );
    await writeFile(
      join(fixture, ".site-build/publications/voxelfix.html"),
      generated + "Must not overwrite",
    );
    await assert.rejects(exportPages(fixture), /unexpected route/);
    assert.equal(await exists(join(fixture, "index.html")), false);
  } finally {
    await rm(fixture, { recursive: true, force: true });
  }
});

test("export preserves handwritten files and refuses to remove them as stale output", async () => {
  const fixture = await mkdtemp(join(tmpdir(), "portfolio-protect-"));
  try {
    await mkdir(join(fixture, ".site-build"), { recursive: true });
    await writeFile(
      join(fixture, ".site-build/index.html"),
      generated + "Home",
    );
    await writeFile(
      join(fixture, "index.html"),
      "Original handwritten content",
    );
    await assert.rejects(exportPages(fixture), /handwritten/);
    assert.equal(
      await readFile(join(fixture, "index.html"), "utf8"),
      "Original handwritten content",
    );
    await writeFile(join(fixture, "index.html"), generated + "Home");
    await mkdir(join(fixture, "writing/manual"), { recursive: true });
    await writeFile(
      join(fixture, "writing/manual/index.html"),
      "Handwritten article",
    );
    await writeFile(
      join(fixture, ".generated-pages.json"),
      '["index.html","writing/manual/index.html"]',
    );
    await assert.rejects(
      exportPages(fixture),
      /Refusing to remove handwritten/,
    );
    assert.equal(
      await readFile(join(fixture, "writing/manual/index.html"), "utf8"),
      "Handwritten article",
    );
  } finally {
    await rm(fixture, { recursive: true, force: true });
  }
});
